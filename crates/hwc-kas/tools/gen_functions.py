"""Generate crates/hwc-kas/src/generated/{table,runtime}.rs from the kas2c function table.

Input: recovered/missions/data/kas_function_table.json (486 entries parsed from Cataclysm's
embedded kas2c function table: KAS name, C name, return flag, parameter names and types).
Only the interface (names and parameter types) is emitted -- no game logic.

    python crates/hwc-kas/tools/gen_functions.py [path/to/kas_function_table.json]
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.normpath(os.path.join(HERE, '..'))
ROOT = os.path.normpath(os.path.join(CRATE, '..', '..'))
SRC = os.path.join(ROOT, 'recovered', 'missions', 'data', 'kas_function_table.json')
OUT = os.path.join(CRATE, 'src', 'generated')

PTYPE = {
    'GROWSELECTIONPTR': 'Ships', 'SDWORD': 'Int', 'CHARPTR': 'Str', 'VECTORPTR': 'Point',
    'UDWORD': 'Hash', 'AITEAMPTR': 'Team', 'VOLUMEPTR': 'Volume', 'BOOL': 'Bool', 'PATHPTR': 'Path',
}
RUST_ARG = {
    'Ships': 'Ships', 'Int': 'i32', 'Str': "Str<'_>", 'Point': 'Point', 'Hash': 'Hash',
    'Team': 'Team', 'Volume': 'Option<Hash>', 'Bool': 'i32', 'Path': 'Option<Hash>',
}
ACCESSOR = {
    'Ships': 'ships', 'Int': 'int', 'Str': 'str', 'Point': 'point', 'Hash': 'hash',
    'Team': 'team', 'Volume': 'volume', 'Bool': 'int', 'Path': 'path',
}
# Functions the interpreter implements itself (KAS runtime state: variables, timers, team message
# queues, the KAS pause, Random's range logic).
BUILTINS = {
    'TimerCreate', 'TimerSet', 'TimerStart', 'TimerCreateSetStart', 'TimerStop', 'TimerRemaining',
    'TimerExpired', 'TimerExpiredDestroy', 'TimerDestroy', 'VarCreate', 'VarSet', 'VarCreateSet',
    'VarInc', 'VarDec', 'VarGet', 'VarDestroy', 'MsgSend', 'MsgSendAll', 'MsgReceived',
    'MsgQueueFlush', 'ThisTeamIs', 'Random', 'PauseOtherKAS', 'UnpauseOtherKAS',
}
KEYWORDS = {'as', 'break', 'const', 'continue', 'crate', 'else', 'enum', 'extern', 'false', 'fn', 'for',
            'if', 'impl', 'in', 'let', 'loop', 'match', 'mod', 'move', 'mut', 'pub', 'ref', 'return',
            'self', 'Self', 'static', 'struct', 'super', 'trait', 'true', 'type', 'unsafe', 'use', 'where',
            'while', 'async', 'await', 'dyn', 'abstract', 'become', 'box', 'do', 'final', 'macro',
            'override', 'priv', 'typeof', 'unsized', 'virtual', 'yield', 'try', 'gen', 'cx'}


def snake(name):
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    s = re.sub(r'([a-z])([A-Z])', r'\1_\2', s)
    s = re.sub(r'([0-9])([A-Z][a-z])', r'\1_\2', s)
    s = s.lower()
    if s in KEYWORDS:
        s += '_'
    return s


def builtin_variant(kas):
    return kas


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else SRC
    table = json.load(open(src))
    assert len(table) == 486, len(table)
    os.makedirs(OUT, exist_ok=True)
    hdr = ('// @generated by crates/hwc-kas/tools/gen_functions.py from the kas2c function table.\n'
           '// Do not edit by hand.\n\n')

    # ---- table.rs ------------------------------------------------------------------------
    t = [hdr, 'use crate::functions::{Builtin, FuncInfo, ParamType::*};\n\n',
         '/// The kas2c function table, in the order of the table embedded in cataclysm.exe\n',
         '/// (the index is the [`FuncId`](crate::functions::FuncId)).\n',
         'pub static FUNCTIONS: [FuncInfo; %d] = [\n' % len(table)]
    for k, e in enumerate(table):
        assert e['n'] == len(e['params']), e
        params = ', '.join('("%s", %s)' % (p[0], PTYPE[p[1]]) for p in e['params'])
        b = 'Some(Builtin::%s)' % builtin_variant(e['kas']) if e['kas'] in BUILTINS else 'None'
        t.append('    FuncInfo { kas: "%s", c: "%s", returns: %s, params: &[%s], builtin: %s },  // %d\n' % (
            e['kas'], e['c'], 'true' if e['ret'] else 'false', params, b, k))
    t.append('];\n')
    open(os.path.join(OUT, 'table.rs'), 'w', newline='\n').write(''.join(t))

    # ---- runtime.rs ----------------------------------------------------------------------
    used = {}
    r = [hdr,
         'use crate::functions::FuncId;\n',
         'use crate::host::{Cx, Point, Ships, Str, Team, Value};\n',
         'use crate::Hash;\n\n',
         '/// The game-side KAS runtime functions: one method per kas2c table entry that the\n',
         '/// simulation implements (variables, timers, messages, `ThisTeamIs`, `Random` and the KAS\n',
         '/// pause are handled by the interpreter itself and do not appear here).\n',
         '///\n',
         '/// Every method has a default body that reports the call to [`KasRuntime::unhandled`] and\n',
         '/// returns 0, so a host can implement only what it supports and missions still run headless.\n',
         '/// `cx` carries the calling context (the current team, `CurrentTeamP` in the original).\n',
         '#[allow(unused_variables)]\n',
         'pub trait KasRuntime {\n',
         '    /// Called by every default method: an unimplemented runtime function. Returns the\n',
         '    /// value the call evaluates to (the default is 0).\n',
         '    fn unhandled(&mut self, cx: &Cx, func: FuncId) -> i32 {\n',
         '        0\n',
         '    }\n']
    disp = ['\n/// Calls the host method for table entry `id` with already evaluated arguments.\n',
            '/// Builtins and out-of-range ids go to [`KasRuntime::unhandled`].\n',
            'pub(crate) fn dispatch<H: KasRuntime + ?Sized>(h: &mut H, cx: &Cx, id: FuncId, a: &[Value<\'_>]) -> i32 {\n',
            '    let arg = |i: usize| a.get(i).copied().unwrap_or(Value::Int(0));\n',
            '    match id.0 {\n']
    for k, e in enumerate(table):
        if e['kas'] in BUILTINS:
            continue
        m = snake(e['kas'])
        if m in used:
            m = snake(e['kas']) + '_%d' % k
        used[m] = k
        pnames = []
        for p in e['params']:
            pn = snake(p[0])
            while pn in pnames:
                pn += '_'
            pnames.append(pn)
        args = ''.join(', %s: %s' % (pn, RUST_ARG[PTYPE[p[1]]]) for pn, p in zip(pnames, e['params']))
        sig = '(%s)' % ', '.join('%s %s' % (p[1], p[0]) for p in e['params'])
        ret = ' -> i32' if e['ret'] else ''
        r.append('\n    /// `%s%s` (`%s`, table index %d)%s.\n' % (
            e['kas'], sig, e['c'], k, '; returns a value' if e['ret'] else ''))
        r.append('    fn %s(&mut self, cx: &Cx%s)%s {\n' % (m, args, ret))
        if e['ret']:
            r.append('        self.unhandled(cx, FuncId(%d))\n' % k)
        else:
            r.append('        self.unhandled(cx, FuncId(%d));\n' % k)
        r.append('    }\n')
        call_args = ''.join(', arg(%d).%s()' % (i, ACCESSOR[PTYPE[p[1]]]) for i, p in enumerate(e['params']))
        if e['ret']:
            disp.append('        %d => h.%s(cx%s),\n' % (k, m, call_args))
        else:
            disp.append('        %d => {\n            h.%s(cx%s);\n            0\n        }\n' % (k, m, call_args))
    r.append('}\n')
    disp.append('        _ => h.unhandled(cx, id),\n    }\n}\n')
    open(os.path.join(OUT, 'runtime.rs'), 'w', newline='\n').write(''.join(r + disp))
    print('generated %d entries, %d host methods' % (len(table), len(used)))


if __name__ == '__main__':
    main()
