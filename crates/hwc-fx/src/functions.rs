/// Declared type of parameter `index` of an entry. Past the 9 type slots the original reads
/// into the next entry; those slots never occur in the shipped scripts, so they read as INT.
pub fn param_type(entry: &FuncEntry, index: usize) -> u8 {
    entry.types.get(index).copied().unwrap_or(if index < 9 { VOID } else { INT })
}

