/// Compile-time hooks run after a call is parsed.
#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum Resolve {
    None,
    /// `etgCreationResolve`: the following `{ ... }` becomes per-particle callback code.
    Creation,
    /// `etgDepthWriteResolve`: `setDepthWrite(0)` marks the effect sort-forward.
    DepthWrite,
}

/// One row of the function table.
#[derive(Clone, Copy, Debug, serde::Serialize, serde::Deserialize)]
pub struct FuncEntry {
    pub name: &'static str,
    pub fun: Fun,
    pub ret: u8,
    pub pass_this: bool,
    pub resolve: Resolve,
    pub types: &'static [u8],
}

const fn e(name: &'static str, fun: Fun, ret: u8, pass_this: bool, resolve: Resolve, types: &'static [u8]) -> FuncEntry {
    FuncEntry { name, fun, ret, pass_this, resolve, types }
}

